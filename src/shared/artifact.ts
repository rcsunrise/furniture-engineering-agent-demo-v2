import { z } from "zod";

export type ArtifactType =
  | "ai_reference_mesh"
  | "cad_profile"
  | "3d_geometry"
  | "preview_image"
  | "bom_table"
  | "inference_report";

export interface ArtifactProvenance {
  provider: string;
  workflowVersion?: string;
  modelOrCheckpoint?: string;
  seed?: number;
  inputAssetHash?: string;
  outputArtifactHash?: string;
  createdAt: string;
}

export interface EngineeringArtifact {
  id: string;
  type: ArtifactType;
  name: string;
  uri?: string;
  provenance: ArtifactProvenance;
  productionTruth: boolean;
}

export const ArtifactProvenanceSchema = z.object({
  provider: z.string(),
  workflowVersion: z.string().optional(),
  modelOrCheckpoint: z.string().optional(),
  seed: z.number().optional(),
  inputAssetHash: z.string().optional(),
  outputArtifactHash: z.string().optional(),
  createdAt: z.string(),
}).strict();

export const EngineeringArtifactSchema = z.object({
  id: z.string(),
  type: z.enum([
    "ai_reference_mesh",
    "cad_profile",
    "3d_geometry",
    "preview_image",
    "bom_table",
    "inference_report",
  ]),
  name: z.string(),
  uri: z.string().optional(),
  provenance: ArtifactProvenanceSchema,
  productionTruth: z.boolean(),
}).strict();

/**
  Enforces productionTruth = false for any artifact generated by AI or external compute workers,
  unless explicitly confirmed by manual engineering override.
 */
export function createEngineeringArtifact(
  params: Omit<EngineeringArtifact, "productionTruth"> & { productionTruth?: boolean }
): EngineeringArtifact {
  const isManualConfirmed = params.provenance.provider === "MANUAL_ENGINEERING_CONFIRMED";
  const truthValue = isManualConfirmed ? (params.productionTruth ?? true) : false;

  return {
    id: params.id,
    type: params.type,
    name: params.name,
    ...(params.uri ? { uri: params.uri } : {}),
    provenance: { ...params.provenance },
    productionTruth: truthValue,
  };
}
